using AspireDeployService.Core.Deploy;
using AspireDeployService.Core.Discovery;
using AspireDeployService.Core.Settings;
using AspireDeployService.Tests.Support;

namespace AspireDeployService.Tests.Deploy;

/// <summary>
/// Resource pickers plan D3 as revised by T0: the patched copy of a file-based or TypeScript AppHost lives in a
/// sibling <c>.ads-deploy</c> folder under the same file name.
/// </summary>
public class SiblingOverlayTests : IDisposable
{
    private readonly TempDir _dir = new();

    public void Dispose() => _dir.Dispose();

    [Theory]
    [InlineData("apphost.cs")]
    [InlineData("apphost.ts")]
    [InlineData("apphost.mts")]
    public void Sibling_keeps_the_name_in_a_sibling_folder(string name) =>
        Assert.Equal(Path.Combine("C:\\src", ".ads-deploy", name), SiblingOverlay.SiblingPath(Path.Combine("C:\\src", name)));

    [Fact]
    public void Cleanup_deletes_only_folders_whose_copy_has_the_marker()
    {
        _dir.Write("a/.ads-deploy/apphost.cs", SiblingOverlay.Marker + "\nvar x = 1;");
        _dir.Write("a/.ads-deploy/.aspire/modules/aspire.mts", "generated by the CLI");
        _dir.Write("b/.ads-deploy/apphost.mts", SiblingOverlay.Marker + "\r\nconst x = 1;");
        var userFolder = _dir.Write("c/.ads-deploy/apphost.cs", "// my own file\n");
        var markerLater = _dir.Write("d/.ads-deploy/apphost.ts", "// first\n" + SiblingOverlay.Marker);
        var otherName = _dir.Write("e/other/apphost.cs", SiblingOverlay.Marker);
        var inNodeModules = _dir.Write("node_modules/x/.ads-deploy/apphost.ts", SiblingOverlay.Marker);

        var deleted = SiblingOverlay.CleanupLeftovers(_dir.Path);

        Assert.Equal(new[] { _dir.Combine("a", ".ads-deploy"), _dir.Combine("b", ".ads-deploy") }.Order(), deleted.Order());
        Assert.False(Directory.Exists(_dir.Combine("a", ".ads-deploy")));
        Assert.True(File.Exists(userFolder));
        Assert.True(File.Exists(markerLater));
        Assert.True(File.Exists(otherName));
        Assert.True(File.Exists(inNodeModules));
    }

    [Fact]
    public void Cleanup_of_a_missing_folder_is_empty() =>
        Assert.Empty(SiblingOverlay.CleanupLeftovers(_dir.Combine("missing")));

    [Fact]
    public void Remove_deletes_only_our_folder()
    {
        var ours = _dir.Write("a/.ads-deploy/apphost.cs", SiblingOverlay.Marker + "\n");
        Assert.True(SiblingOverlay.Remove(ours));
        Assert.False(Directory.Exists(_dir.Combine("a", ".ads-deploy")));

        var theirs = _dir.Write("b/.ads-deploy/apphost.cs", "// mine\n");
        Assert.False(SiblingOverlay.Remove(theirs));
        Assert.True(File.Exists(theirs));

        Assert.True(SiblingOverlay.Remove(_dir.Combine("none", ".ads-deploy", "apphost.cs")));
    }

    [Fact]
    public void Scanner_ignores_a_leftover_copy_as_a_second_AppHost()
    {
        const string code = "#:sdk Aspire.AppHost.Sdk@13.6.1\n#:package Aspire.Hosting.Azure.AppContainers@13.6.1\n"
            + "var builder = DistributedApplication.CreateBuilder(args);\nbuilder.AddAzureContainerAppEnvironment(\"env\");\nbuilder.Build().Run();\n";
        _dir.Write("apphost.cs", code);
        _dir.Write(".ads-deploy/apphost.cs", SiblingOverlay.Marker + "\n" + code);

        var scan = AppHostScanner.Scan(_dir.Path, null, AspireDeployOptions.From(new AspireDeploySection()));

        Assert.Equal("apphost.cs", scan.AppHost.AppHostPath);
    }
}
